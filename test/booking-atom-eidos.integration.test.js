const {test}=require('node:test');
const assert=require('node:assert/strict');
const express=require('express');
const {fixture}=require('./helpers/music-ontology-fixture.cjs');
const {Eidos,registerEidos}=require('../src/eden-eidos');
const {BookingAtomEidos,BOOKING_ATOMS}=require('../src/booking-atom-eidos');

test('every Booking atom has a stable, independent Eidos; deletion stays permanent until explicit re-seeding',{timeout:120000},async t=>{
 const db=await fixture();t.after(()=>db.stop());
 const app=express();app.use(express.json());
 const requireAdmin=(req,res,next)=>req.headers.authorization==='Bearer admin'?next():res.sendStatus(401);
 registerEidos(app,{requireAdmin});require('../src/tree-of-truth').registerTree(app,{requireAdmin});
 const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));t.after(()=>new Promise(resolve=>server.close(resolve)));
 const origin=`http://127.0.0.1:${server.address().port}`,endpoint=origin+'/api/admin/eden/eidos';
 const request=async(method='GET',body,suffix='')=>{const res=await fetch(endpoint+suffix,{method,headers:{Authorization:'Bearer admin','Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return{status:res.status,body:await res.json()};};
 assert.equal(new Set(BOOKING_ATOMS.map(row=>row.atomId)).size,BOOKING_ATOMS.length);
 assert.ok(BOOKING_ATOMS.some(row=>row.atomId==='event.venue.latitude'));
 assert.equal((await fetch(endpoint+'/booking-atoms',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).status,401);
 assert.equal((await request('POST',{atomId:'invented'},'/booking-atoms')).status,400);
 const manual=(await request('POST',{fourthGoal:'Keep this independent seed.'})).body.item;
 const seeded=await Promise.all([request('POST',{},'/booking-atoms'),request('POST',{},'/booking-atoms')]);
 for(const result of seeded)assert.equal(result.status,200,JSON.stringify(result.body));
 assert.equal(seeded.reduce((sum,result)=>sum+result.body.created,0),BOOKING_ATOMS.length);
 let result=await request(),links=result.body.bookingAtoms;
 assert.equal(links.length,BOOKING_ATOMS.length);assert.equal(new Set(links.map(row=>row.eidosId)).size,BOOKING_ATOMS.length);
 const original=new Map(links.map(row=>[row.atomId,row.eidosId]));
 for(const atom of BOOKING_ATOMS)assert.ok(original.has(atom.atomId),atom.atomId);
 const dateId=original.get('event.date');
 assert.equal((await request('PUT',{fourthGoal:'Preserve the chosen purpose.',previousFourthGoal:''},'/'+dateId)).status,200);
 const again=await request('POST',{},'/booking-atoms');assert.equal(again.body.created,0);assert.deepEqual(new Map(again.body.bookingAtoms.map(row=>[row.atomId,row.eidosId])),original);
 assert.equal(again.body.items.find(row=>row.id===dateId).fourthGoal,'Preserve the chosen purpose.');
 assert.equal(again.body.items.find(row=>row.id===manual.id).fourthGoal,'Keep this independent seed.');
 const snapshot=await (await fetch(origin+'/api/tree')).json();assert.equal(snapshot.atomEidos.length,BOOKING_ATOMS.length);assert.equal(JSON.stringify(snapshot).includes('Preserve the chosen purpose.'),false);
 assert.equal((await request('DELETE',{permanent:true,previousFourthGoal:'stale'},'/'+dateId)).status,409);
 assert.ok(await BookingAtomEidos.exists({atomId:'event.date',eidosId:dateId}));
 const deleted=await request('DELETE',{permanent:true,previousFourthGoal:'Preserve the chosen purpose.'},'/'+dateId);assert.equal(deleted.status,200);
 assert.equal(await Eidos.findOne({externalId:dateId}),null);assert.equal(await BookingAtomEidos.findOne({eidosId:dateId}),null);
 for(let i=0;i<2;i++)assert.equal((await request()).body.bookingAtoms.some(row=>row.atomId==='event.date'),false);
 assert.equal((await (await fetch(origin+'/api/tree')).json()).atomEidos.length,BOOKING_ATOMS.length-1);
 const explicit=await request('POST',{},'/booking-atoms');assert.equal(explicit.status,200);assert.equal(explicit.body.created,1);
 const replacement=explicit.body.bookingAtoms.find(row=>row.atomId==='event.date').eidosId;assert.notEqual(replacement,dateId);
 for(const row of explicit.body.bookingAtoms)if(row.atomId!=='event.date')assert.equal(row.eidosId,original.get(row.atomId));
 assert.equal(await BookingAtomEidos.countDocuments(),BOOKING_ATOMS.length);
 assert.equal(await Eidos.countDocuments({externalId:dateId}),0);
});
