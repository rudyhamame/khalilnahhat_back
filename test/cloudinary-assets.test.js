const {test}=require('node:test');
const assert=require('node:assert/strict');
const {Writable}=require('node:stream');
const mongoose=require('mongoose');
const fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path'),net=require('node:net');
const {spawn,spawnSync}=require('node:child_process');
const {Asset,createAssetStore,identityOptions,referenced,hasReferences,sweep}=require('../src/cloudinary-assets');
test('stable identities deduplicate across folders and separate delivery policies',()=>{
 const hash='a'.repeat(64);
 assert.equal(identityOptions(hash,{folder:'Gallery',resource_type:'image'}).public_id,identityOptions(hash,{folder:'khalil/equipment',resource_type:'image'}).public_id);
 assert.notEqual(identityOptions(hash,{resource_type:'image'}).public_id,identityOptions(hash,{resource_type:'image',type:'authenticated'}).public_id);
 assert.equal(identityOptions(hash,{resource_type:'raw',public_id:'random.glb'}).public_id.endsWith('.glb'),true);
 const asset={cloud:'qa',resourceType:'video',delivery:'authenticated',publicId:'folder/abc'};
 assert.ok(referenced({nested:['https://res.cloudinary.com/qa/video/authenticated/s--signature--/c_limit/v123/folder/abc.mp3']},asset));
 assert.equal(referenced('https://res.cloudinary.com/other/video/authenticated/folder/abc.mp3',asset),false);
 assert.equal(referenced('https://res.cloudinary.com/qa/video/authenticated/folder/abcd.mp3',asset),false);
});
test('uploads, shared references, direct DB deletion, failed cleanup and upload/delete races',{timeout:60000},async t=>{
 if(spawnSync('mongod',['--version'],{stdio:'ignore'}).status!==0)return t.skip('mongod required');
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'echo-asset-test-'));
 const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
 const mongo=spawn('mongod',['--bind_ip','127.0.0.1','--port',String(port),'--dbpath',dir,'--logpath',path.join(dir,'mongo.log')],{stdio:'ignore'});
 t.after(async()=>{await mongoose.disconnect();mongo.kill('SIGTERM');await new Promise(resolve=>mongo.exitCode!==null?resolve():mongo.once('exit',resolve));await fs.rm(dir,{recursive:true,force:true});});
 await mongoose.connect(`mongodb://127.0.0.1:${port}/asset_test`,{serverSelectionTimeoutMS:15000});await Asset.init();
 let uploads=0,failDelete=false;const deleted=[];
 const client={config:()=>({cloud_name:'qa'}),uploader:{upload_stream:(opts,done)=>new Writable({write(chunk,enc,next){next();},final(next){uploads++;done(null,{secure_url:`https://res.cloudinary.com/qa/${opts.resource_type}/${opts.type||'upload'}/v1/${opts.public_id}.png`,public_id:opts.public_id,resource_type:opts.resource_type,bytes:5});next();}}),destroy:async(id,opts)=>{if(failDelete)throw Error('offline');deleted.push({id,opts});return {result:'ok'};}}};
 const store=createAssetStore({client});
 const options={folder:'Gallery',resource_type:'image'};
 const first=await Promise.all([store.upload(Buffer.from('hello'),options),store.upload(Buffer.from('hello'),{...options,folder:'khalil/equipment'})]);
 assert.equal(uploads,1);assert.equal(first[0].secure_url,first[1].secure_url);
 await store.upload(Buffer.from('hello'),options);assert.equal(uploads,1);
 const db=mongoose.connection.db;
 await db.collection('owners').insertMany([{name:'gallery',url:first[0].secure_url},{name:'equipment',image:first[0].secure_url}]);
 let row=await Asset.findOne().lean();assert.ok(await hasReferences(row));
 await Asset.updateOne({_id:row._id},{$set:{holdUntil:new Date(0)}});
 await db.collection('owners').deleteOne({name:'gallery'});
 await sweep({client});assert.equal(deleted.length,0,'shared image preserved');
 await db.collection('owners').deleteMany({});
 const later=new Date(Date.now()+60*60*1000);
 await sweep({client,now:later});assert.equal(deleted.length,0,'grace period');
 failDelete=true;await sweep({client,now:new Date(+later+6*60*1000)});
 row=await Asset.findOne().lean();assert.equal(row.attempts,1);assert.equal(row.state,'ready');assert.match(row.lastError,/offline/);
 failDelete=false;await sweep({client,now:new Date(+later+7*60*1000)});
 assert.equal(deleted.length,1);assert.equal(deleted[0].opts.invalidate,true);assert.equal(await Asset.countDocuments(),0);
 await store.upload(Buffer.from('hello'),options);assert.equal(uploads,2,'deleted file can be uploaded again');
 row=await Asset.findOne().lean();await Asset.updateOne({_id:row._id},{$set:{holdUntil:new Date(0),missingSince:new Date(0)}});
 let checks=0;await sweep({client,now:later,check:async()=>++checks===2});assert.equal(deleted.length,1,'second reference check prevents deletion');
 await Asset.updateOne({_id:row._id},{$set:{state:'deleting'}});
 await assert.rejects(store.upload(Buffer.from('hello'),options),/being cleaned up/);
 await Asset.updateOne({_id:row._id},{$set:{state:'ready',holdUntil:new Date(0),missingSince:new Date(0)}});
 await sweep({client,now:later,check:async()=>{throw Error('DB unavailable');}});assert.equal(deleted.length,1,'fail closed when reference scan fails');
});
