const {test}=require('node:test');
const assert=require('node:assert/strict');
const mongoose=require('mongoose');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const net=require('node:net');
const {spawn,spawnSync}=require('node:child_process');

test('real API preserves each broadcast metadata in MongoDB and does not deduplicate across sessions',{timeout:90000},async t=>{
 assert.equal(spawnSync('mongod',['--version'],{stdio:'ignore'}).status,0,'mongod required');
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'live-session-metadata-'));
 const port=await new Promise(resolve=>{const server=net.createServer();server.listen(0,'127.0.0.1',()=>{const port=server.address().port;server.close(()=>resolve(port));});});
 const mongo=spawn('mongod',['--bind_ip','127.0.0.1','--port',String(port),'--dbpath',dir,'--logpath',path.join(dir,'mongo.log')],{stdio:'ignore'});
 t.after(async()=>{await mongoose.disconnect();mongo.kill('SIGTERM');await new Promise(resolve=>mongo.exitCode!==null?resolve():mongo.once('exit',resolve));await fs.rm(dir,{recursive:true,force:true});});
 await mongoose.connect(`mongodb://127.0.0.1:${port}/live_metadata_isolated_test`,{serverSelectionTimeoutMS:20000});
 const {app}=require('../src/server');
 const {User,LiveSession,LiveRequest,LiveStreamConfig}=require('../src/models');
 const {LiveRecording}=require('../src/live-recordings');
 const {ADMIN_USERNAME,defaultLiveStreamConfig}=require('../src/default-data');
 const {hashPassword}=require('../src/security');
 await Promise.all([User,LiveSession,LiveRequest,LiveStreamConfig].map(Model=>Model.init()));
 const admin=await User.create({username:ADMIN_USERNAME,email:'metadata@example.invalid',firstName:'Metadata',lastName:'QA',phoneNumber:'000',passwordHash:await hashPassword('Isolated-test-only-2026'),isAdmin:true});
 const token=await require('../src/account-sessions').issueSession(admin,{headers:{}},require('../src/admin-role').isAdminUser);
 await LiveStreamConfig.create({...defaultLiveStreamConfig,isLive:true,broadcastMode:'webrtc',broadcastSource:'browser',webrtcRoomName:'metadata-a'});
 const recording=await LiveRecording.create({roomName:'metadata-a',title:'First live'});
 const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));t.after(()=>new Promise(resolve=>server.close(resolve)));
 const call=async(url,method='GET',body)=>{const response=await fetch(`http://127.0.0.1:${server.address().port}/api${url}`,{method,headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return {code:response.status,data:await response.json()};};
 const comment=await call('/live-comments','POST',{session:'metadata-a',text:'First live comment'});assert.equal(comment.code,201);
 const manual=await call('/live-sessions','POST',{session:'metadata-a',track:'Manual first live track'});assert.equal(manual.code,201);
 const approve=async session=>{
  assert.equal((await call('/live-suggestions','POST',{session,track:'Same requested song',artist:'Session artist'})).code,201);
  const request=await LiveRequest.findOne({broadcastSessionId:session});
  const review=await call('/live-requests/'+request.externalId+'/review','PATCH',{session,decision:'approved'});
  assert.equal(review.code,200,JSON.stringify(review.data));assert.equal(review.data.item.requestStatus,'approved');
  assert.equal((await LiveSession.findOne({requestExternalId:request.externalId})).broadcastSessionId,session);
 };
 await approve('metadata-a');
 assert.equal((await call('/bootstrap')).data.liveSessions.length,2);
 await LiveStreamConfig.updateOne({},{$set:{isLive:false,webrtcRoomName:''}});
 assert.deepEqual((await call('/bootstrap')).data.liveSessions,[]);
 assert.deepEqual((await call('/live-sessions')).data,{session:null,items:[]});
 assert.deepEqual((await call('/live-comments')).data.items,[]);
 await LiveStreamConfig.updateOne({},{$set:{isLive:true,webrtcRoomName:'metadata-b'}});
 assert.deepEqual((await call('/bootstrap')).data.liveSessions,[]);
 assert.deepEqual((await call('/live-requests/admin?broadcast=current')).data.items,[]);
 assert.deepEqual((await call('/live-comments?session=metadata-b')).data.items,[]);
 await approve('metadata-b');
 const current=await call('/live-sessions?session=metadata-b');assert.equal(current.data.items.length,1);assert.equal(current.data.items[0].broadcastSessionId,'metadata-b');
 assert.equal((await call('/live-sessions/'+manual.data.item.id,'PATCH',{session:'metadata-b',track:'Wrong session edit'})).code,404);
 const archived=await call(`/admin/live-recordings/${recording._id}/metadata`);
 assert.equal(archived.code,200);assert.equal(archived.data.session,'metadata-a');assert.equal(archived.data.setList.length,2);assert.equal(archived.data.requests.length,1);assert.equal(archived.data.comments[0].text,'First live comment');
});
